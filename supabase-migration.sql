create unique index if not exists catalogo_tmdb_tipo_uidx
  on public.catalogo (tipo, tmdb_id) where tmdb_id is not null;

-- Avaliações e comentários: um registo por visitante e título.
create table if not exists public.catalogo_feedback (
  id bigint generated by default as identity primary key,
  app_id text not null,
  visitor_id text not null,
  avaliacao integer null check (avaliacao between 1 and 5),
  comentario text not null default '',
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint catalogo_feedback_app_visitor_uidx unique (app_id, visitor_id)
);
create index if not exists catalogo_feedback_app_id_idx on public.catalogo_feedback (app_id, criado_em desc);

-- Contagem de pessoas únicas que abriram um título ou chegaram aos 20 minutos finais.
create table if not exists public.catalogo_eventos (
  id bigint generated by default as identity primary key,
  app_id text not null,
  visitor_id text not null,
  tipo_evento text not null check (tipo_evento in ('click','completed')),
  criado_em timestamptz not null default now(),
  constraint catalogo_eventos_unique unique (app_id, visitor_id, tipo_evento)
);
create index if not exists catalogo_eventos_app_id_idx on public.catalogo_eventos (app_id, tipo_evento);

alter table public.catalogo_feedback enable row level security;
alter table public.catalogo_eventos enable row level security;
drop policy if exists "feedback public read" on public.catalogo_feedback;
create policy "feedback public read" on public.catalogo_feedback for select using (true);
drop policy if exists "feedback public insert" on public.catalogo_feedback;
create policy "feedback public insert" on public.catalogo_feedback for insert with check (length(visitor_id) between 1 and 100 and length(app_id) between 1 and 200 and (avaliacao is null or avaliacao between 1 and 5) and length(comentario) <= 800);
drop policy if exists "feedback public update" on public.catalogo_feedback;
create policy "feedback public update" on public.catalogo_feedback for update using (true) with check (length(visitor_id) between 1 and 100 and length(app_id) between 1 and 200 and (avaliacao is null or avaliacao between 1 and 5) and length(comentario) <= 800);
drop policy if exists "events public read" on public.catalogo_eventos;
create policy "events public read" on public.catalogo_eventos for select using (true);
drop policy if exists "events public insert" on public.catalogo_eventos;
create policy "events public insert" on public.catalogo_eventos for insert with check (length(visitor_id) between 1 and 100 and length(app_id) between 1 and 200 and tipo_evento in ('click','completed'));
